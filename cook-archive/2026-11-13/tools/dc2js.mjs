// Convert DayXero v4 .dc.html character/scene components into plain JS SVG generators.
import fs from 'node:fs';
const src = 'design/handoff/canvas/project/';
const comps = { xero: 'Xero', jelli: 'Jelli', glim: 'Glim2', horizon: 'Horizon2' };
let out = `// Generated by cook/tools/dc2js.mjs from design/handoff/canvas/project (v4 components). Do not edit by hand.
(function(){
class DCLogic { constructor(p){ this.props = p || {}; this.state = null; } }
let uid = 0;
function fill(tpl, vals){ return tpl.replace(/\\{\\{([\\w.$]+)\\}\\}/g, (m, k) => { let v = vals; for (const p of k.split('.')) v = v == null ? '' : v[p]; return v == null ? '' : String(v); }); }
function uniq(svg){ const n = ++uid; const ids = [...svg.matchAll(/id="([^"]+)"/g)].map(m => m[1]); for (const id of ids){ svg = svg.split('id="'+id+'"').join('id="'+id+'_'+n+'"').split('url(#'+id+')').join('url(#'+id+'_'+n+')').split('href="#'+id+'"').join('href="#'+id+'_'+n+'"'); } return svg; }
const DXC = window.DXC = {};
`;
for (const [k, f] of Object.entries(comps)) {
  const t = fs.readFileSync(src + f + '.dc.html', 'utf8');
  const tpl = t.slice(t.indexOf('<svg'), t.lastIndexOf('</svg>') + 6);
  const props = JSON.parse(t.match(/data-props='([^']*)'/)[1]);
  const defaults = Object.fromEntries(Object.entries(props).filter(([p]) => !p.startsWith('$')).map(([p, v]) => [p, v.default]));
  const code = t.slice(t.indexOf('class Component'), t.lastIndexOf('</script>'));
  out += `DXC.${k} = (function(){ const TPL = ${JSON.stringify(tpl)}; const DEF = ${JSON.stringify(defaults)};
${code.replace('class Component', 'const Component = class')}
return function(p){ const c = new Component(Object.assign({}, DEF, p || {})); return uniq(fill(TPL, c.renderVals())); }; })();
`;
}
out += `})();\n`;
fs.writeFileSync('cook/site/kit/chars.js', out);
console.log('wrote', out.length);
